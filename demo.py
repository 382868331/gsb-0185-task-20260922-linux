"""Deterministic offline demo for csg_rays.

Scenes (generated by this file, no external data), all results below are
computed live by ray_intervals; the hand-derived annotations are checks:

1. Hollow sphere with material ids: Difference(outer r=5 steel, inner r=2
   air).  The cavity walls are the subtractor's faces with flipped normals;
   every boundary carries its leaf material and a front/back/grazing
   orientation.
2. Nested difference A - (B - C) with concentric balls (r=10/6/2): the
   inner-most leaf C sits at even subtractor depth and is NOT flipped, while
   B is.  Hand-derived solid runs from -20: t in (10,14), (18,22), (26,30).
3. Two balls tangent at one point: the closed-solid union is one continuous
   run, so the shared tangent endpoint creates no phantom boundary; a ray one
   radius above instead reports two isolated grazing touches.
4. Genuinely triggered input rejections (invalid input is never silently
   corrected, and no half-built object is left behind).

Run:  python demo.py     (finishes in well under 90 seconds)
"""

from csg_rays import (
    Difference,
    GeometryError,
    Ray,
    Sphere,
    Union,
    ray_intervals,
)


def show(result, label):
    print(f"--- {label} ---")
    for iv in result.intervals:
        print(f"  solid interval ({iv.t0:g}, {iv.t1:g})")
    if not result.intervals:
        print("  (no solid intervals)")
    for touch in result.touches:
        print(f"  zero-measure touch at t={touch.t0:g}..{touch.t1:g}")
    for b in result.boundaries:
        s = b.source
        normal = "(" + ", ".join(f"{c:g}" for c in s.normal) + ")"
        material = s.material if s.material is not None else "-"
        print(
            f"  t={b.t:>6g}  {b.kind:<5} leaf={s.leaf_id:<5} mat={material:<5} "
            f"orient={s.orientation:<7} normal={normal} flipped={s.flipped}"
        )
    nearest = result.nearest_boundary
    if nearest is None:
        print("  nearest forward boundary (t>0): none")
    else:
        print(
            f"  nearest forward boundary (t>0): t={nearest.t:g} "
            f"{nearest.kind} on leaf {nearest.source.leaf_id!r} "
            f"mat {nearest.source.material!r}"
        )


def main():
    # 1) Hollow sphere with materials.
    hollow = Difference(
        Sphere((0, 0, 0), 5, "outer", "steel"),
        Sphere((0, 0, 0), 2, "inner", "air"),
    )
    res = ray_intervals(hollow, Ray((-10, 0, 0), (1, 0, 0)))
    show(res, "hollow sphere (outer=steel, cavity=air), ray (-10,0,0)+t(1,0,0)")
    print("  hand check: intervals (5,8),(12,15); cavity walls flipped,")
    print("              t=8 enter front->normal +x, t=12 exit back->normal -x")
    print()

    # 2) Nested difference A - (B - C): parity of subtractor depth.
    nested = Difference(
        Sphere((0, 0, 0), 10, "A", "mA"),
        Difference(
            Sphere((0, 0, 0), 6, "B", "mB"),
            Sphere((0, 0, 0), 2, "C", "mC"),
        ),
    )
    res2 = ray_intervals(nested, Ray((-20, 0, 0), (1, 0, 0)))
    show(res2, "nested A-(B-C), concentric r=10/6/2, ray (-20,0,0)+t(1,0,0)")
    print("  hand check: solid (10,14),(18,22),(26,30); B flipped (depth 1),")
    print("              C not flipped (depth 2, even)")
    print()

    # 3a) Externally tangent balls: closed union is continuous through the
    #     shared tangent point -> one interval, no phantom boundary.
    tangent = Union([
        Sphere((0, 0, 0), 2, "a", "red"),
        Sphere((4, 0, 0), 2, "b", "blue"),
    ])
    res3 = ray_intervals(tangent, Ray((-5, 0, 0), (1, 0, 0)))
    show(res3, "two balls tangent at x=2: union along the x-axis")
    print("  hand check: one interval (3,11); tangent point t=7 swallowed")
    print()

    # 3b) Same two balls, ray one radius above: two isolated grazing touches,
    #     empty on both sides (zero measure, not interior).
    res4 = ray_intervals(tangent, Ray((-5, 2, 0), (1, 0, 0)))
    show(res4, "same balls, ray grazing both tops at y=2")
    print("  hand check: touches at t=5 and t=9, both orientation=grazing")
    print()

    # 4) Genuinely triggered rejections.
    print("--- invalid input rejections ---")
    try:
        Ray((0, 0, 0), (0, 0, 0))
    except GeometryError as exc:
        print(f"  zero direction rejected: {exc}")
    try:
        Sphere((0, 0, 0), float("nan"), "bad", "steel")
    except GeometryError as exc:
        print(f"  NaN radius rejected:      {exc}")
    try:
        Sphere((0, 0, 0), 1, "bad", 7)  # material must be None or non-empty str
    except GeometryError as exc:
        print(f"  bad material rejected:    {exc}")


if __name__ == "__main__":
    main()
