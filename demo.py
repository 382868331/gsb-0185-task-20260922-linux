"""Deterministic offline demo for csg_rays (material-id / orientation iteration).

Scenes are generated by this file with small integer inputs, no external data
and no pre-recorded answers: every printed number comes from ray_intervals.

Run:  python demo.py     (finishes in well under 90 seconds)
"""

from csg_rays import (
    Box,
    Difference,
    GeometryError,
    Ray,
    Sphere,
    Union,
    ray_intervals,
)


def show(result, label):
    print(f"--- {label} ---")
    for iv in result.intervals:
        print(f"  solid interval ({iv.t0:g}, {iv.t1:g})")
    if not result.intervals:
        print("  (no solid intervals)")
    for touch in result.touches:
        span = f"t={touch.t0:g}" if touch.t0 == touch.t1 else f"t={touch.t0:g}..{touch.t1:g}"
        print(f"  zero-measure touch {span}")
        for s in touch.sources:
            normal = "(" + ", ".join(f"{c:g}" for c in s.normal) + ")"
            print(
                f"      face={s.face:<6} leaf={s.leaf_id:<5} material={s.material:<7}"
                f" orientation={s.orientation:<7} normal={normal} flipped={s.flipped}"
            )
    for b in result.boundaries:
        for s in b.sources:
            normal = "(" + ", ".join(f"{c:g}" for c in s.normal) + ")"
            print(
                f"  t={b.t:>5g}  {b.kind:<5} face={s.face:<6} leaf={s.leaf_id:<5}"
                f" material={s.material:<7} orientation={s.orientation:<7}"
                f" normal={normal} flipped={s.flipped}"
            )
    nearest = result.nearest_boundary
    if nearest is None:
        print("  nearest forward boundary (t>0): none")
    else:
        s = nearest.source
        print(
            f"  nearest forward boundary (t>0): t={nearest.t:g} {nearest.kind}"
            f" on leaf {s.leaf_id!r} material={s.material!r}"
        )
    print()


def main():
    # 1) Nested difference A - (B - C), concentric spheres r=20/10/5, each
    #    surface carrying its own material id.  The cavity wall of B is
    #    authored inward with a flipped geometric normal; C is the positive
    #    of the inner difference, so its parity toggles back to outward.
    tree = Difference(
        Sphere((0, 0, 0), 20, "A", material="steel"),
        Difference(
            Sphere((0, 0, 0), 10, "B", material="brass"),
            Sphere((0, 0, 0), 5, "C", material="copper"),
        ),
    )
    show(
        ray_intervals(tree, Ray((-25, 0, 0), (1, 0, 0))),
        "A - (B - C), concentric r=20/10/5: nested-difference facing parity",
    )

    # 2) Per-face materials on a box: the entry face x_lo is painted red while
    #    every other face keeps the box default plastic.
    box = Box(
        (0, 0, 0), (2, 2, 2), "box",
        material="plastic", face_materials={"x_lo": "red"},
    )
    show(
        ray_intervals(box, Ray((-1, 1, 1), (1, 0, 0))),
        "box with a per-face material override (x_lo=red)",
    )

    # 3) Coincident endpoint with a fixed representative priority: a union of
    #    two face-to-face boxes merges into one interval and the shared face
    #    creates no phantom boundary.
    a = Box((0, 0, 0), (2, 2, 2), "aa", material="m_aa")
    b = Box((2, 0, 0), (4, 2, 2), "bb", material="m_bb")
    show(
        ray_intervals(Union([a, b]), Ray((-1, 1, 1), (1, 0, 0))),
        "face-to-face union: coincident shared face, no phantom boundary",
    )

    # 4) Tangent boundary: the ray rides the positive box face while a
    #    subtractor sphere grazes it.  The contact stays one zero-measure
    #    touch; the subtractor surface is inward-authored but its geometric
    #    normal at a touch is the real outward one (flipped=False).
    a = Box((0, 0, 0), (4, 2, 2), "A", material="steel")
    sub = Sphere((2, 3, 1), 1, "B", material="brass")
    show(
        ray_intervals(Difference(a, sub), Ray((-1, 2, 1), (1, 0, 0))),
        "tangent subtractor on a face-riding contact",
    )

    # 5) A genuinely triggered rejection: an unknown face-override key is a
    #    construction error (never silently dropped), so no half-configured
    #    primitive can reach ray_intervals.
    print("--- invalid input rejection ---")
    try:
        Box((0, 0, 0), (1, 1, 1), "bad", face_materials={"w_lo": "red"})
    except GeometryError as exc:
        print(f"  unknown face key rejected: {exc}")


if __name__ == "__main__":
    main()
