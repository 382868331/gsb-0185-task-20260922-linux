"""Deterministic offline demo for csg_rays.

All scenes are generated by this file (no external data, no credentials):

1. the original hollow sphere (Difference of two concentric balls);
2. one shared unit-ball subtree reused in three places -- an analytic
   ellipsoid (non-uniform scale), a translated copy and a mirrored
   subtractor inside a Difference -- showing per-reference transforms,
   inverse-transpose normals, mirrored enter/exit that are NOT swapped;
3. two genuinely triggered input rejections (a singular instance matrix
   and a reference cycle), proving invalid structures are not corrected.

Run:  ./.venv/bin/python demo.py   (finishes in well under a second)
"""

from csg_rays import (
    Box,
    Difference,
    GeometryError,
    Instance,
    Ray,
    Sphere,
    Union,
    ray_intervals,
)


def show(result, label):
    print(f"--- {label} ---")
    for iv in result.intervals:
        print(f"  solid interval ({iv.t0:g}, {iv.t1:g})")
    if not result.intervals:
        print("  (no solid intervals)")
    for touch in result.touches:
        print(f"  zero-measure touch at t={touch.t0:g}..{touch.t1:g}")
    for b in result.boundaries:
        s = b.source
        normal = "(" + ", ".join(f"{c:g}" for c in s.normal) + ")"
        path = "/".join(s.path) or "-"
        print(
            f"  t={b.t:>6g}  {b.kind:<5} face={s.face:<6} leaf={s.leaf_id:<6}"
            f" path={path:<12} normal={normal} flipped={s.flipped}"
        )
    nearest = result.nearest_boundary
    if nearest is None:
        print("  nearest forward boundary (t>0): none")
    else:
        print(
            f"  nearest forward boundary (t>0): t={nearest.t:g} "
            f"{nearest.kind} on leaf {nearest.source.leaf_id!r} "
            f"via path {nearest.source.path or '()'}"
        )


def main():
    # 1) Hollow sphere, ray through the cavity.
    hollow = Difference(
        Sphere((0, 0, 0), 5, "outer"),
        Sphere((0, 0, 0), 2, "inner"),
    )
    res = ray_intervals(hollow, Ray((-10, 0, 0), (1, 0, 0)))
    show(res, "hollow sphere, ray (-10,0,0) + t*(1,0,0)")
    print()

    # 2) One shared subtree, reused three times with different transforms:
    #    a scaled ellipsoid at the origin, a translated copy at +9 and a
    #    mirrored-and-translated copy at -9.  All three share one node.
    unit_ball = Sphere((0, 0, 0), 1, "ball")
    ellipsoid = Instance(
        unit_ball,
        ((2, 0, 0), (0, 3, 0), (0, 0, 1)),  # x^2/4 + y^2/9 + z^2 = 1
        (0, 0, 0),
        "ell",
    )
    translated = Instance(
        unit_ball, ((1, 0, 0), (0, 1, 0), (0, 0, 1)), (9, 0, 0), "shift"
    )
    mirrored = Instance(
        unit_ball, ((-1, 0, 0), (0, 1, 0), (0, 0, 1)), (-9, 0, 0), "mirror"
    )
    res2 = ray_intervals(
        Union([ellipsoid, translated, mirrored]), Ray((0, 0, 0), (1, 0, 0))
    )
    show(res2, "one shared unit ball: ellipsoid@0, copy@+9, mirrored copy@-9")
    print("  ell: scaled sphere hit at t = +-2; mirror: enter/exit are not")
    print("  swapped by the negative determinant (normal points outward).")
    print()

    # 2b) The same node reused as a mirrored subtractor: a hole centered at
    #     local +3 lands at world -3; its face normals flip at the correct
    #     (Difference) level and point into the cavity.
    hole = Sphere((3, 0, 0), 1, "hole")
    shell = Difference(
        Sphere((0, 0, 0), 5, "shell"),
        Instance(hole, ((-1, 0, 0), (0, 1, 0), (0, 0, 1)), (0, 0, 0), "mh"),
    )
    res2b = ray_intervals(shell, Ray((0, 0, 0), (1, 0, 0)))
    show(res2b, "shell r=5 minus the mirrored hole (cavity centered at -3)")
    print("  cavity walls at t=-4 (normal +x) and t=-2 (normal -x): flipped")
    print("  subtractor normals point into the cavity; mirror geometry intact.")
    print()

    # 3) Sheared box: inverse-transpose normal on the slanted face.
    cube = Box((-1, -1, -1), (1, 1, 1), "cube")
    sheared = Instance(
        cube, ((1, 1, 0), (0, 1, 0), (0, 0, 1)), (0, 0, 0), "sh"
    )
    res3 = ray_intervals(sheared, Ray((-4, 0, 0), (1, 0, 0)))
    show(res3, "sheared unit cube, ray along x (slab -1 <= x-y <= 1)")
    print("  slanted face normals are inverse-transpose images: (+-1,-+1,0)/sqrt2")
    print()

    # 4) Genuinely triggered rejections.
    print("--- invalid input rejections ---")
    try:
        Instance(
            unit_ball,
            ((1, 2, 3), (4, 5, 6), (7, 8, 9)),  # determinant 0
            (0, 0, 0),
            "degenerate",
        )
    except GeometryError as exc:
        print(f"  singular matrix rejected: {exc}")

    cyc = Instance(unit_ball, ((1, 0, 0), (0, 1, 0), (0, 0, 1)),
                   (0, 0, 0), "self")
    wrapper = Union([Box((0, 0, 0), (1, 1, 1), "b"), cyc])
    object.__setattr__(cyc, "child", wrapper)  # a cycle cannot be built normally
    try:
        ray_intervals(cyc, Ray((0, 0, 0), (1, 0, 0)))
    except GeometryError as exc:
        print(f"  reference cycle rejected: {exc}")
    print()

    # 5) Live, timed computation at a bounded scale: one shared hollow-ball
    #    subtree (3 nodes) referenced 24 times, i.e. 1 union + 24 instances
    #    + 24*3 referenced nodes = 97 <= MAX_TREE_NODES (100), probed by
    #    400 rays.  Deterministic placement; this is an interface-boundary
    #    stress check, not a proof of any performance number beyond this run.
    import time

    shared_hollow = Difference(
        Sphere((0, 0, 0), 2, "outer"), Sphere((0, 0, 0), 1, "inner")
    )
    refs = [
        Instance(
            shared_hollow,
            ((1, 1 if k % 3 == 0 else 0, 0), (0, 1, 0), (0, 0, 1)),
            ((k % 8) * 6 - 21, (k // 8) * 6 - 9, 0),
            f"c{k}",
        )
        for k in range(24)
    ]
    crowd = Union(refs)
    t0 = time.perf_counter()
    n_intervals = 0
    n_boundaries = 0
    n_rays = 400
    for i in range(n_rays):
        r = ray_intervals(
            crowd,
            Ray((-28, -12 + (i % 24), 0), (1, (i % 5) - 2, (i % 3) - 1)),
        )
        n_intervals += len(r.intervals)
        n_boundaries += len(r.boundaries)
    elapsed = time.perf_counter() - t0
    print("--- live bounded-scale computation ---")
    print(
        f"  {n_rays} rays vs 97-node expanded tree "
        f"(24 references of one shared hollow subtree)"
    )
    print(
        f"  total solid intervals: {n_intervals}, "
        f"boundaries: {n_boundaries}, elapsed: {elapsed*1000:.1f} ms "
        f"(time budget for this demo: 90 s)"
    )


if __name__ == "__main__":
    main()
