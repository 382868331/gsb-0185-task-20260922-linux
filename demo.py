"""Deterministic offline demo for csg_rays.

Scene (generated by this file, no external data): a hollow sphere -- a solid
outer ball of radius 5 with a concentric spherical cavity of radius 2 --
probed by two rays, followed by two genuinely triggered input rejections.

Run:  python demo.py     (finishes in well under 8 seconds)
"""

from csg_rays import Difference, GeometryError, Ray, Sphere, ray_intervals


def show(result, label):
    print(f"--- {label} ---")
    for iv in result.intervals:
        print(f"  solid interval ({iv.t0:g}, {iv.t1:g})")
    if not result.intervals:
        print("  (no solid intervals)")
    for touch in result.touches:
        print(f"  zero-measure touch at t={touch.t0:g}..{touch.t1:g}")
    for b in result.boundaries:
        s = b.source
        normal = "(" + ", ".join(f"{c:g}" for c in s.normal) + ")"
        print(
            f"  t={b.t:>6g}  {b.kind:<5} face={s.face:<6} leaf={s.leaf_id:<6}"
            f" normal={normal} flipped={s.flipped}"
        )
    nearest = result.nearest_boundary
    if nearest is None:
        print("  nearest forward boundary (t>0): none")
    else:
        print(
            f"  nearest forward boundary (t>0): t={nearest.t:g} "
            f"{nearest.kind} on leaf {nearest.source.leaf_id!r}"
        )


def main():
    # A solid with a cavity: outer ball minus inner ball (closed subtractor).
    hollow = Difference(
        Sphere((0, 0, 0), 5, "outer"),
        Sphere((0, 0, 0), 2, "inner"),
    )

    # 1) Ray through the hollow sphere: enters the shell, exits into the
    #    cavity, re-enters the shell, exits -- cavity in/out faces are the
    #    inner sphere's faces with flipped normals.
    res = ray_intervals(hollow, Ray((-10, 0, 0), (1, 0, 0)))
    show(res, "hollow sphere, ray (-10,0,0) + t*(1,0,0)")
    print("  cavity entry face: t=8  exit  normal=(1, 0, 0) -> points into cavity")
    print("  cavity exit  face: t=12 enter normal=(-1, 0, 0) -> points into cavity")
    print()

    # 2) Ray starting inside the cavity itself.
    res2 = ray_intervals(hollow, Ray((0, 0, 0), (1, 0, 0)))
    show(res2, "ray starting inside the cavity, origin (0,0,0)")
    print()

    # 3) Two genuinely triggered rejections (invalid input is not corrected).
    print("--- invalid input rejections ---")
    try:
        Ray((0, 0, 0), (0, 0, 0))
    except GeometryError as exc:
        print(f"  zero direction rejected: {exc}")
    try:
        Sphere((0, 0, 0), float("nan"), "bad")
    except GeometryError as exc:
        print(f"  NaN radius rejected:   {exc}")


if __name__ == "__main__":
    main()
