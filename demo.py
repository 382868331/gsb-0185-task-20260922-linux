"""Deterministic offline demo for csg_rays (instanced subtrees).

Scenes (generated by this file, no external data):

1. one reusable CSG subtree -- a unit ball with a thin bar -- is placed in
   the scene twice through Instance references: once unchanged, once scaled
   2x and translated.  The shared node is never copied or mutated; each
   reported boundary is qualified by its instance path plus the original
   leaf id.
2. the same subtree placed under a reflection (negative determinant): the
   enter/exit order stays correct and normals point the right way.
3. a genuinely triggered invalid-transform rejection (a singular matrix).

Run:  python demo.py     (finishes in well under a second)
"""

import time

from csg_rays import GeometryError, Instance, Ray, Union, ray_intervals
from csg_rays import Box, Sphere


def show(result, label):
    print(f"--- {label} ---")
    for iv in result.intervals:
        print(f"  solid interval ({iv.t0:g}, {iv.t1:g})")
    if not result.intervals:
        print("  (no solid intervals)")
    for touch in result.touches:
        print(f"  zero-measure touch at t={touch.t0:g}..{touch.t1:g}")
    for b in result.boundaries:
        s = b.source
        normal = "(" + ", ".join(f"{c:g}" for c in s.normal) + ")"
        path = "/" + "/".join(s.path) if s.path else "/<root>"
        print(
            f"  t={b.t:>5g}  {b.kind:<5} face={s.face:<6} "
            f"leaf={s.leaf_id:<5} path={path:<6} normal={normal}"
        )


def main():
    started = time.perf_counter()

    # Reusable subtree: unit ball at origin plus a thin bar on its -x side,
    # locally the solid covers x in [-2, 1] (at y,z in [0,1] for the bar).
    ball_bar = Union([
        Sphere((0, 0, 0), 1, "ball"),
        Box((-2, 0, 0), (-1, 1, 1), "bar"),
    ])

    ident = [[1, 0, 0], [0, 1, 0], [0, 0, 1]]

    # 1) two references to the same subtree: original placement and a
    #    2x-scaled, translated placement.
    two_placements = Union([
        Instance(ball_bar, ident, (0, 0, 0), "orig"),
        Instance(ball_bar,
                 [[2, 0, 0], [0, 2, 0], [0, 0, 2]], (10, 0, 0), "big"),
    ])
    ray = Ray((-5, 0.5, 0.5), (1, 0, 0))
    res = ray_intervals(two_placements, ray)
    show(res, "one subtree referenced twice (orig + 2x scaled at x=10)")
    print("  expected: orig bar (3,4) + ball (4.29,5.71); "
          "big copy bar (11,13) + ball (13.13,16.87)")
    print()

    # 2) reflection in x: x_w = 10 - x_l (det = -1).  The ball maps to
    #    center x=10 and the bar to world x in [11,12]; along a +x ray the
    #    first crossing is still an enter, never an enter/exit swap, and the
    #    face normals come out mirrored (bar enter normal is -x).
    mirrored = Instance(
        ball_bar, [[-1, 0, 0], [0, 1, 0], [0, 0, 1]], (10, 0, 0), "mirror"
    )
    res2 = ray_intervals(mirrored, Ray((5, 0.5, 0.5), (1, 0, 0)))
    show(res2, "same subtree mirrored (det=-1): ball (4.29,5.71), bar (6,7)")
    print("  expected: two intervals; every enter normal points against +x")
    print()

    # 3) a singular instance transform must be rejected up front.
    print("--- invalid transform rejection ---")
    try:
        Instance(ball_bar, [[1, 2, 3], [4, 5, 6], [7, 8, 9]], (0, 0, 0), "bad")
    except GeometryError as exc:
        print(f"  singular matrix rejected: {exc}")

    print(f"\nelapsed: {time.perf_counter() - started:.3f} s")


if __name__ == "__main__":
    main()
