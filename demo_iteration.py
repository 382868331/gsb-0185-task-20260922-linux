"""Deterministic offline demo for the finite Cylinder leaf of csg_rays.

Scenes (generated by this file, no external data):
1. a finite cylinder minus a central sphere (cylindrical shell with a
   spherical cavity),
2. the intersection of an axis-aligned box with a cylinder,
3. zero-measure contacts: a ray tangent to the lateral surface and a ray
   that only grazes a cap edge circle.

Everything is computed live (well under 90 seconds; in practice
milliseconds).  Run:  python demo_iteration.py
"""

from csg_rays import (
    Box,
    Cylinder,
    Difference,
    GeometryError,
    Intersection,
    Ray,
    Sphere,
    ray_intervals,
)


def show(result, label):
    print(f"--- {label} ---")
    for iv in result.intervals:
        print(f"  solid interval ({iv.t0:g}, {iv.t1:g})")
    if not result.intervals:
        print("  (no solid intervals)")
    for touch in result.touches:
        faces = ", ".join(sorted(s.face for s in touch.sources))
        print(f"  zero-measure touch at t={touch.t0:g}..{touch.t1:g}  faces={faces}")
    for b in result.boundaries:
        s = b.source
        normal = "(" + ", ".join(f"{c:g}" for c in s.normal) + ")"
        print(
            f"  t={b.t:>6g}  {b.kind:<5} face={s.face:<6} leaf={s.leaf_id:<6}"
            f" normal={normal} flipped={s.flipped}"
        )
    nearest = result.nearest_boundary
    if nearest is None:
        print("  nearest forward boundary (t>0): none")
    else:
        print(
            f"  nearest forward boundary (t>0): t={nearest.t:g} "
            f"{nearest.kind} on leaf {nearest.source.leaf_id!r}"
        )


def main():
    # 1) Finite cylinder (radius 1, caps z=-2..3) minus a central sphere.
    #    The ray runs along the x axis through the center: it crosses the
    #    lateral surface, then the spherical cavity walls (flipped normals).
    shell = Difference(
        Cylinder((0, 0, 0), 1, -2, 3, "cyl"),
        Sphere((0, 0, 0), 0.5, "ball"),
    )
    res = ray_intervals(shell, Ray((0, 0, 0), (1, 0, 0)))
    show(res, "cylinder minus sphere, ray (0,0,0) + t*(1,0,0)")
    print("  cavity walls are the sphere's faces with flipped normals")
    print()

    # 2) Box intersected with a cylinder: the box clips the y extent, the
    #    cylinder contributes the z caps; ray along the y axis.
    capped = Intersection([
        Box((-2, -1, -5), (2, 1, 5), "box"),
        Cylinder((0, 0, 0), 3, -2, 3, "cyl"),
    ])
    res2 = ray_intervals(capped, Ray((0, -10, 0), (0, 1, 0)))
    show(res2, "box intersected with cylinder, ray (0,-10,0) + t*(0,1,0)")
    print()

    # 3) Zero-measure contacts of the same cylinder.
    cyl = Cylinder((0, 0, 0), 1, -2, 3, "cyl")
    res3 = ray_intervals(cyl, Ray((-5, 1, 0), (1, 0, 0)))
    show(res3, "ray tangent to the lateral surface (y = radius)")
    res4 = ray_intervals(cyl, Ray((-5, 1, -2), (1, 0, 0)))
    show(res4, "ray grazing only the bottom cap edge circle")
    print()

    # 4) A genuinely triggered rejection (invalid input is not corrected).
    print("--- invalid input rejection ---")
    try:
        Cylinder((0, 0, 0), 1, 3, -2, "bad")
    except GeometryError as exc:
        print(f"  z_hi <= z_lo rejected: {exc}")


if __name__ == "__main__":
    main()
